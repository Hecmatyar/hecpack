// What /init would write into a project for one level, as file contents. Nothing here touches the disk:
// the preview writes these into its own folder, /init into the project.

export const LEVELS = ['lite', 'standard', 'deep'];

export const LEVEL_INFO = {
  lite: 'Session rules, triage, the stack and validation commands; the checker agent.',
  standard: 'Lite plus the architect loop (analysis before M tasks, review after every task), the thinker and the project map.',
  deep: 'Standard plus the chain of chats, sub-sessions with a coordinator and model limits per agent.',
};

const HOME = '.claude/hecpack';
const core = (file) => `hecpack:core/${file}`;

const contextMap = (level, rules = []) => {
  const stack = `${HOME}/stack.md`;
  const map = `${HOME}/project-map.md`;
  const types = {
    q: [core('session.md'), stack],
    code:
      level === 'lite'
        ? [core('session.md'), `${core('workflow.md')}#Triage`, stack, ...rules]
        : [core('session.md'), core('workflow.md'), stack, map, ...rules],
  };
  const tags = { q: 'q', code: 'code', s: 'code', m: 'code' };
  const keywords = {};
  if (level === 'deep') {
    types.coord = [core('session.md'), core('workflow.md'), core('coordination.md'), stack, map];
    types.code.push(`${core('coordination.md')}#Chain of chats`);
    tags.coord = 'coord';
    keywords.coord = ['coordinate', 'coordinator', 'sub-sessions'];
  }
  const agents = { 'hecpack:checker': [stack] };
  if (level !== 'lite') {
    agents['hecpack:architect'] = [stack, map, ...rules];
    agents['hecpack:thinker'] = [stack, map];
  }
  return {
    $comment: 'Generated by hecpack. Files injected by its context hook: per prompt type (a tag like [S], [M], [q] picks it; untagged prompts get `untagged`) and per agent. `hecpack:` paths live in the plugin, the rest in this project; add your own rule files to the lists.',
    limit: 10000,
    parts: { prompt: 4, agent: 4 },
    untagged: 'code',
    tags,
    keywords,
    types,
    agents,
  };
};

const config = ({ level, language, techs, rules = [] }) => ({
  $comment: 'Generated by hecpack. level and language are yours to change; agentModels limits the model an Agent call may pick per agent.',
  level,
  language,
  thresholds: { freshSession: 180000, coordinatorClear: 150000 },
  agentModels: {
    'hecpack:checker': { model: 'sonnet' },
    ...(level === 'lite'
      ? {}
      : { 'hecpack:architect': { model: 'opus' }, 'hecpack:thinker': { model: 'opus' } }),
  },
  techs: techs.map((tech) => tech.id),
  rules,
});

// The level to propose: deep for a monorepo with several workspaces (long tasks, parallel sessions pay off),
// standard when there is a real stack to keep in shape, lite for a small project with no tests yet.
export const recommendLevel = (detection) => {
  const ids = new Set(detection.techs.map((tech) => tech.id));
  const monorepo = ['nx', 'turborepo', 'pnpm-workspaces'].some((id) => ids.has(id)) || detection.workspaces.length >= 3;
  if (monorepo) return { level: 'deep', reason: 'a monorepo with several workspaces: long tasks and parallel sessions pay off' };
  const tests = ['jest', 'vitest', 'playwright', 'cypress', 'maestro'].some((id) => ids.has(id));
  if (detection.techs.length >= 3 || tests) return { level: 'standard', reason: 'a real stack with tests: the architect loop and the project map pay off' };
  return { level: 'lite', reason: 'a small project: rules, triage and checks are enough to start' };
};

// Optional modules on top of a level, each one file the user may or may not want.
export const MODULES = {
  'git-safety': {
    label: 'Git safety',
    description: 'Denies destructive git commands (stash, reset, checkout, clean, restore, rebase, commit, push, pull) in .claude/settings.json; the user runs them. The Wayfarer way: uncommitted changes are intentional and stay as they are.',
  },
};

const DESTRUCTIVE_GIT = ['stash', 'reset', 'checkout', 'clean', 'restore', 'rebase', 'commit', 'push', 'pull'];

// The project's settings.json with the deny rules added; everything else in it is kept as it is.
export const gitSafetySettings = (text) => {
  const settings = text ? JSON.parse(text) : {};
  const rules = DESTRUCTIVE_GIT.flatMap((verb) => [`Bash(git ${verb})`, `Bash(git ${verb} *)`, `Bash(git -C * ${verb} *)`]);
  const deny = settings.permissions?.deny ?? [];
  settings.permissions = { ...settings.permissions, deny: [...deny, ...rules.filter((rule) => !deny.includes(rule))] };
  return settings;
};

const SOURCE_LINE = {
  pack: (source) => `hecpack pack ${source.id} (${source.status})`,
  plugin: (source) => `plugin ${source.id}${source.enabled ? ' (on)' : ''}`,
  docs: (source) => `context7${source.enabled ? '' : ' (not set up)'}`,
  'local-skill': (source) => `local skill ${source.id}/SKILL.md (to write)`,
};

const stackMd = ({ detection, techs, sources, date, rules = [] }) => {
  const byTech = Object.fromEntries(sources.map((item) => [item.tech, item.sources]));
  const lines = [
    '# Stack',
    '',
    `Generated by hecpack on ${date} from the project's manifests. Keep it current: a task that changes the stack updates this file.`,
    '',
    '## Technologies',
    '',
    ...techs.map((tech) => {
      const list = (byTech[tech.id] ?? []).map((source) => SOURCE_LINE[source.kind](source));
      return `- ${tech.label}${tech.version ? ` ${tech.version}` : ''} (${tech.kind}). Sources: ${list.join('; ') || 'none'}.`;
    }),
    '',
    '## Validation',
    '',
  ];
  if (detection.validation.length) {
    for (const item of detection.validation) {
      lines.push(`- ${item.check}: \`${item.command}\`${item.scoped ? `; one project: \`${item.scoped}\`` : ''} (from ${item.source}).`);
    }
    lines.push('', 'Run the narrowest command that covers the changed files; the full run before a task is reported done.');
  } else {
    lines.push('- No validation commands found. Add the typecheck, lint and test commands here.');
  }
  lines.push(
    '',
    '## Docs',
    '',
    'The installed versions above may be newer than your knowledge. For a library API, check the docs of that version (context7: resolve-library-id, then query-docs) or the package source in `node_modules`; never memory.',
  );
  if (rules.length) {
    lines.push('', '## Project rules', '', 'Rule files of this project the context hook also loads for code tasks and the architect (listed in `context-map.json`):', '');
    for (const rule of rules) lines.push(`- \`${rule}\``);
  }
  const gaps = techs.filter((tech) => (byTech[tech.id] ?? []).some((source) => source.kind === 'local-skill'));
  if (gaps.length) {
    lines.push('', '## Gaps', '', 'No rules yet for these; until a skill covers them, follow the existing code in the same area:', '');
    for (const tech of gaps) lines.push(`- ${tech.label}: ${tech.covers.filter((slot) => slot !== 'docs' && slot !== 'validation').join(', ')}.`);
  }
  return `${lines.join('\n')}\n`;
};

const projectMapMd = ({ detection, date }) => {
  const lines = [
    '# Project map',
    '',
    `Generated by hecpack on ${date}. One line per folder: what lives there and what must not. Fill in the empty descriptions; a task that adds, renames or removes a folder listed here updates this file.`,
  ];
  for (const unit of detection.folders) {
    lines.push('', `## ${unit.path} (${unit.name})`, '');
    if (unit.description) lines.push(unit.description, '');
    if (!unit.children.length) lines.push('- (no subfolders)');
    for (const child of unit.children) lines.push(`- \`${child}\`: `);
  }
  return `${lines.join('\n')}\n`;
};

export const CLAUDE_SECTION_HEADING = '## hecpack';

const claudeSection = (level) =>
  [
    CLAUDE_SECTION_HEADING,
    '',
    `This project uses the hecpack plugin at the ${level} level. Its rules load automatically through its hooks from \`${HOME}/context-map.json\`; the project's own specifics (stack, validation, folders) live in \`${HOME}/\`. Keep them there rather than in this file.`,
    '',
  ].join('\n');

const withSection = (text, section) => {
  const start = text.indexOf(`\n${CLAUDE_SECTION_HEADING}\n`);
  if (start === -1) return `${text.replace(/\n*$/, '\n')}\n${section}`;
  const end = text.indexOf('\n## ', start + 1);
  return `${text.slice(0, start + 1)}${section}${end === -1 ? '' : text.slice(end)}`;
};

export const warnings = (claude) => {
  const out = [];
  const contextHooks = claude.hookEvents.filter((event) => ['UserPromptSubmit', 'SubagentStart', 'SessionStart'].includes(event));
  if (contextHooks.length) {
    out.push({
      id: 'hooks',
      text: `The project already runs its own hooks on ${contextHooks.join(', ')}. With hecpack on, both run and the rules may load twice; keep one source per rule.`,
    });
  }
  const clash = claude.agents.filter((name) => ['architect', 'thinker', 'checker'].includes(name));
  if (clash.length) {
    out.push({
      id: 'agents',
      text: `The project has its own agents named ${clash.join(', ')}. hecpack's are hecpack:architect, hecpack:thinker, hecpack:checker; a brief has to name which one it means.`,
    });
  }
  if (claude.hecpack) out.push({ id: 'existing', text: 'hecpack is already set up here; the diff compares with the current files.' });
  return out;
};

// readProject(path) returns the project's current text of a file, or undefined. `rules` are the project's own
// rule files to load with the core (paths relative to the root); `modules` the optional MODULES to add.
export const plan = ({ detection, sources, level, language = 'en', techIds, rules = [], modules = [], readProject, date }) => {
  for (const id of modules) if (!MODULES[id]) throw new Error(`unknown module: ${id} (known: ${Object.keys(MODULES).join(', ')})`);
  const techs = techIds ? detection.techs.filter((tech) => techIds.includes(tech.id)) : detection.techs;
  const chosen = sources.filter((item) => techs.some((tech) => tech.id === item.tech));
  const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
  const claudeMd = detection.claude.claudeMd[0] ?? 'CLAUDE.md';
  const files = [
    { path: `${HOME}/config.json`, content: json(config({ level, language, techs, rules })), note: 'level, language, thresholds, models per agent' },
    { path: `${HOME}/context-map.json`, content: json(contextMap(level, rules)), note: 'which rules load for which task and agent' },
    { path: `${HOME}/stack.md`, content: stackMd({ detection, techs, sources: chosen, date, rules }), note: 'technologies, versions, validation, gaps' },
    ...(level === 'lite' ? [] : [{ path: `${HOME}/project-map.md`, content: projectMapMd({ detection, date }), note: 'folder index to fill in' }]),
    { path: claudeMd, content: withSection(readProject(claudeMd) ?? '', claudeSection(level)), note: 'one short section pointing to hecpack' },
  ];
  if (modules.includes('git-safety')) {
    files.push({ path: '.claude/settings.json', content: json(gitSafetySettings(readProject('.claude/settings.json'))), note: 'deny rules for destructive git commands', module: 'git-safety' });
  }
  return files.map((file) => {
    const before = readProject(file.path);
    return { ...file, action: before === undefined ? 'create' : before === file.content ? 'same' : 'update' };
  });
};
